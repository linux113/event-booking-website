#!/usr/bin/env node
/**
 * Builds `docs/one-shot-schema.sql` — the whole schema as one statement batch, for a
 * hosted SQL editor that takes a paste instead of a file (Neon, Supabase, RDS…).
 *
 *   node scripts/build-one-shot-schema.mjs
 *
 * Order: the prelude (auth.users + auth.uid()), the 16 migrations in filename order,
 * and — with `--seed` — supabase/seed.sql. The batch is wrapped in a single
 * transaction, so a failure anywhere leaves the database exactly as it was, not
 * half-migrated. Nothing in the migrations needs to run outside a transaction
 * (`create index concurrently`, `vacuum`, `create database` are all absent — the
 * build fails if that ever changes).
 *
 * The batch finishes by recording what it applied in `setup.applied_migrations`, the
 * same bookkeeping `npm run db:setup` keeps, so a later `db:setup` knows this work is
 * already done and only applies what is new. Migrations are forward-only (two of them
 * change a function's return shape), so the paste is a once-per-database action: a
 * second paste fails harmlessly on the first restated function and changes nothing.
 *
 * The output is generated, not hand-written: re-run this after adding a migration.
 */
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "docs/one-shot-schema.sql");
const withSeed = process.argv.includes("--seed");

const NOT_TRANSACTIONAL = /^\s*(create\s+(unique\s+)?index\s+concurrently|vacuum|create\s+database|alter\s+system|drop\s+database)\b/im;

const files = [
  ["prelude.sql", join(ROOT, "supabase/prelude.sql")],
  ...readdirSync(join(ROOT, "supabase/migrations"))
    .filter((name) => name.endsWith(".sql"))
    .sort()
    .map((name) => [name, join(ROOT, "supabase/migrations", name)]),
  ...(withSeed ? [["seed.sql", join(ROOT, "supabase/seed.sql")]] : []),
];

const parts = [
  "-- ---------------------------------------------------------------------------",
  "-- one-shot-schema.sql — GENERATED by scripts/build-one-shot-schema.mjs.",
  "-- Do not edit: edit the migrations and rebuild.",
  "--",
  `-- The whole schema in one statement batch: ${files.length} sections, wrapped in a`,
  "-- single transaction, so it either all applies or none of it does.",
  "--",
  "-- How to use it: open your database provider's SQL editor, paste this entire file,",
  "-- and run it. That is the whole installation — no CLI, no driver, no local install.",
  "--",
  "-- Expected notices (not errors): the gallery section reports that it cannot create",
  "-- storage buckets on a plain Postgres, which is correct — Supabase Storage does not",
  "-- exist here.",
  "--",
  "-- Afterwards, check it landed:",
  "--   select (select count(*) from information_schema.tables",
  "--            where table_schema='public' and table_type='BASE TABLE') as tables, -- 11",
  "--          (select count(*) from pg_policies where schemaname='public') as policies, -- 26",
  "--          (select count(*) from pg_class c join pg_namespace n on n.oid=c.relnamespace",
  "--            where n.nspname='public' and c.relkind='r' and c.relrowsecurity) as rls_on; -- 11",
  "-- ---------------------------------------------------------------------------",
  "",
  "begin;",
  "",
];

let lines = 0;

for (const [name, path] of files) {
  const text = readFileSync(path, "utf8");

  if (NOT_TRANSACTIONAL.test(text)) {
    console.error(
      `${path} contains a statement that cannot run inside a transaction — ` +
        `the one-shot batch would fail. Apply it with npm run db:setup instead.`,
    );
    process.exit(1);
  }

  lines += text.split("\n").length;
  parts.push(
    "",
    "-- ===========================================================================",
    `-- ${name}`,
    "-- ===========================================================================",
    "",
    text.trimEnd(),
    "",
  );
}

// The same bookkeeping `npm run db:setup` keeps, so a later setup run skips this work.
const tracking = [
  "",
  "-- ===========================================================================",
  "-- bookkeeping: record what this paste applied",
  "-- ===========================================================================",
  "",
  "create schema if not exists setup;",
  "",
  "create table if not exists setup.applied_migrations (",
  "  filename   text primary key,",
  "  checksum   text,",
  "  applied_at timestamptz not null default now()",
  ");",
  "",
  "insert into setup.applied_migrations (filename, checksum) values",
  files
    .map(
      ([name, path]) =>
        `  ('${name.replace(/'/g, "''")}', '${createHash("sha256").update(readFileSync(path, "utf8"), "utf8").digest("hex")}')`,
    )
    .join(",\n"),
  "on conflict (filename) do nothing;",
  "",
];

parts.push(...tracking, "", "commit;", "");

const output = parts.join("\n");
writeFileSync(OUT, output);

const bytes = Buffer.byteLength(output);
console.log(
  `Wrote docs/one-shot-schema.sql — ${files.length} sections, ${lines} lines of SQL, ` +
    `${(bytes / 1024).toFixed(0)} KB${withSeed ? ", seed included" : " (no seed: rebuild with --seed)"}.`,
);
